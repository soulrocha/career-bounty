import assert from 'node:assert/strict';
import { cp, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import { spawnSync } from 'node:child_process';
import { run, tempDir, repoRoot } from '../helpers/cli.mjs';

test('CLI protege antes da leitura, propõe F5.6 e edita sem aprovar; não existe CLI approve', async t => {
  const root = await tempDir(t);
  await writeFile(path.join(root, 'config.yml'), '{}');
  await cp(path.join(repoRoot, 'tests/fixtures/cv/kb'), path.join(root, 'kb'), { recursive: true });
  const env = { CLAUDE_SESSION_ID: '', CAREER_BOUNTY_NOW: '2026-10-17T12:00:00Z' };
  const command = args => run(['gupy', 'perfil', ...args, '--json'], { dataRoot: root, env });
  const inicio = command(['iniciar', '--aba', '7']);
  assert.equal(inicio.status, 0, inicio.stderr + inicio.stdout);
  assert.equal(inicio.json.protegida, true);
  assert.equal(JSON.parse(await readFile(path.join(root, 'state/perfil-gupy.json'))).abas[0].perfil, null);
  const envelope = { tool_name: 'mcp__claude-in-chrome__javascript_tool', tool_input: { tabId: 7, text: inicio.json.script }, session_id: 'sessao-01', tool_use_id: 'tool-read-01' };
  const linked = spawnSync(process.execPath, [path.join(repoRoot, 'hooks/pre-tool-use.mjs')], { input: JSON.stringify(envelope), encoding: 'utf8', env: { ...process.env, ...env, DATA_ROOT: root } });
  assert.equal(JSON.parse(linked.stdout).hookSpecificOutput.permissionDecision, 'allow');
  const extracao = path.join(root, 'extracao.json'), proposta = path.join(root, 'proposta.json');
  await writeFile(extracao, JSON.stringify({ versao: 'synthetic-v1', origem: 'https://login.gupy.io', perfil_id: 'profile-01', leitura_id: 'documento-01', sobre: '', experiencias: [], habilidades: ['Scrum'] }));
  const raw = JSON.stringify({ tipo: 'proposta', portal: 'gupy', secoes: [{ campo: 'habilidades', proposto: ['Scrum', 'indicadores'], afirmacoes: ['AF-202', 'AF-211', 'AF-212'] }] });
  await writeFile(proposta, raw);
  const observado = spawnSync(process.execPath, [path.join(repoRoot, 'hooks/post-tool-use.mjs')], { input: JSON.stringify({ ...envelope, tool_response: JSON.parse(await readFile(extracao, 'utf8')) }), encoding: 'utf8', env: { ...process.env, ...env, DATA_ROOT: root } });
  assert.equal(observado.status, 0, observado.stderr);
  const d = command(['propor', '--aba', '7', '--extracao', extracao, '--proposta', proposta]);
  assert.equal(d.status, 0, d.stdout);
  const editar = command(['editar', '--aba', '7', '--secao', 'habilidades', '--hash', d.json.itens[0].hash]);
  assert.equal(editar.status, 0, editar.stdout);
  assert.equal(typeof editar.json.script, 'string');
  assert.equal(JSON.parse(await readFile(path.join(root, 'state/perfil-gupy.json'))).abas[0].itens[0].token, null);
  assert.equal(command(['aprovar', '--aba', '7']).status, 2);
  assert.equal(command(['confirmar', '--aba', '7', '--secao', 'habilidades', '--extracao', extracao]).status, 2);
  assert.equal(await readFile(proposta, 'utf8'), raw);
  const hook = (name, input) => {
    const r = spawnSync(process.execPath, [path.join(repoRoot, `hooks/${name}.mjs`)], { input: JSON.stringify(input), encoding: 'utf8', env: { ...process.env, ...env, DATA_ROOT: root } });
    assert.equal(r.status, 0, r.stderr); return JSON.parse(r.stdout);
  };
  const mensagem = `aprovar perfil ${d.json.proposta_hash} ${JSON.stringify([{ secao: 'habilidades', hash: d.json.itens[0].hash }])}`;
  assert.match(hook('user-prompt-submit', { prompt: mensagem, session_id: 'sessao-02' }).hookSpecificOutput.additionalContext, /0 item/);
  assert.match(hook('user-prompt-submit', { prompt: mensagem, session_id: 'sessao-01' }).hookSpecificOutput.additionalContext, /1 item/);
  const change = { name: 'javascript_tool', input: { tabId: 7, text: editar.json.script } };
  assert.equal(hook('pre-tool-use', { tool_name: 'mcp__claude-in-chrome__browser_batch', tool_input: { actions: [change, change] }, session_id: 'sessao-01' }).hookSpecificOutput.permissionDecision, 'deny');
  assert.equal(JSON.parse(await readFile(path.join(root, 'state/perfil-gupy.json'))).abas[0].itens[0].token.usada_em, null);
  const request = { tool_name: 'mcp__claude-in-chrome__javascript_tool', tool_input: change.input, session_id: 'sessao-01' };
  assert.equal(hook('pre-tool-use', request).hookSpecificOutput.permissionDecision, 'allow');
  assert.equal(hook('pre-tool-use', request).hookSpecificOutput.permissionDecision, 'deny');
});
